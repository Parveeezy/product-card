/* Создать переменную, которая хранит внутри себя скорость света.
Создать функцию, которая принимает 1 аргумент - скорость, внутри функции происходит проверка:
если переданная скорость выше скорости света — выводим лог "Сверхсветовая скорость",
если ниже — "Субсветовая  скорость"? если равна — "Скорость света" */

const LIGHT_SPEED = 300000;

const checkLightSpeed = (lightSpeed) => {
  if (lightSpeed > LIGHT_SPEED) {
    console.log("Сверхсветовая скорость");
  } else if (lightSpeed < LIGHT_SPEED) {
    console.log("Субсветовая  скорость");
  } else if (lightSpeed === LIGHT_SPEED) {
    console.log("Скорость света");
  } else {
    console.log("Не переданы аргументы при вызове функции");
  }
};

checkLightSpeed(300001)

